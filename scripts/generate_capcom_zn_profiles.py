#!/usr/bin/env python3
"""Generate the native Capcom ZN profile table from the pinned media registry."""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

COMMIT = "deb2f54fe7300e7a192690318beb860159bfd52a"
DRIVER = "sony/zn.cpp"
DEFAULT_REGISTRY = Path(__file__).with_name("capcom_zn_boards.json")
DEFAULT_OUTPUT = Path(__file__).resolve().parents[1] / "libpcsxcore/arcade/capcom_zn_profiles.inc"
REQUIRED = {
    "maincpu:rom", "cat702_1", "cat702_2", "countryrom",
    "bankedroms", "audiocpu", "qsound",
}
INPUTS = {"capcom4b", "capcom6b", "plsmaswd", "strider2", "tgmj"}


class ProfileError(Exception):
    pass


def generate(registry: Path) -> str:
    try:
        data = json.loads(registry.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise ProfileError(f"cannot read {registry}: {exc}") from exc
    profiles = data.get("profiles", [])
    candidates = [p for p in profiles if p.get("runtime_candidate")]
    if (data.get("schema_version") != 1 or data.get("driver") != DRIVER
            or data.get("mame_source_commit") != COMMIT or len(profiles) != 47
            or data.get("family_game_count") != 47 or len(candidates) != 43):
        raise ProfileError("registry must be the pinned complete 47-profile Capcom ZN registry with 43 candidates")
    if len({p.get("set") for p in profiles}) != 47:
        raise ProfileError("registry has duplicate or missing set names")
    if sum(p.get("state") == "glpracr_state" for p in profiles) != 2:
        raise ProfileError("reviewed Gallop Racer subclass scope changed")
    if {p.get("set") for p in profiles if p.get("is_bios_root")} != {"coh1000c", "coh3002c"}:
        raise ProfileError("Capcom BIOS root set changed")

    lines = [
        "/* Generated by scripts/generate_capcom_zn_profiles.py; do not edit.",
        f" * MAME {DRIVER} at {COMMIT}; 43 runtime candidates from 47 family GAME entries.",
        " */",
    ]
    seen: set[str] = set()
    for p in sorted(candidates, key=lambda row: row["set"]):
        name = p.get("set")
        if name in seen or p.get("state") != "capcom_zn_state":
            raise ProfileError(f"invalid candidate row {name!r}")
        seen.add(name)
        if p.get("machine") not in {"coh1000c", "coh1002c", "coh3002c"}:
            raise ProfileError(f"unsupported machine config in {name}")
        if p.get("input") not in INPUTS:
            raise ProfileError(f"unimplemented input profile {p.get('input')} in {name}")
        if p.get("board_family") not in {"ZN-1", "ZN-2"}:
            raise ProfileError(f"unrecognized board family in {name}")
        regions = {r["tag"]: r["size"] for r in p.get("rom_regions", [])}
        optional = set(p.get("optional_undumped_regions", []))
        if optional not in (set(), {"upd78081"}) or set(regions) != REQUIRED | optional:
            raise ProfileError(f"source region list changed in {name}: {sorted(regions)}")
        if optional:
            review = p.get("optional_undumped_media_review") or {}
            if (review.get("tag") != "upd78081" or review.get("size") != 0x2000
                    or review.get("filename") != "78081g503.ic655"
                    or review.get("handling") != "omitted_from_media_package_no_substitute"):
                raise ProfileError(f"unreviewed undumped MCU region in {name}")
        if regions["bankedroms"] not in (0x2400000, 0x3000000):
            raise ProfileError(f"unexpected banked ROM geometry in {name}")
        if regions["maincpu:rom"] != 0x80000 or regions["countryrom"] != 0x80000:
            raise ProfileError(f"unexpected BIOS/country geometry in {name}")
        if regions["audiocpu"] != 0x40000 or regions["qsound"] != 0x400000:
            raise ProfileError(f"unexpected audio geometry in {name}")
        files = {r["tag"]: r.get("files", []) for r in p["rom_regions"]}
        if any(len(files.get(tag, [])) != 1 or files[tag][0].get("size") != 8
               for tag in ("cat702_1", "cat702_2")):
            raise ProfileError(f"CAT702 key geometry changed in {name}")
        if p.get("bios_options"):
            if p.get("default_bios") not in p["bios_options"].values():
                raise ProfileError(f"BIOS default changed in {name}")
            bios = p["default_bios"]
        else:
            bios = "fixed"
        parent = p.get("parent") or "none"
        bios_parent = p.get("bios_parent") or "none"
        expected_model = {"coh1000c": "COH1000C", "coh1002c": "COH1002C", "coh3002c": "COH3002C"}[p["machine"]]
        if p.get("board_model") != expected_model:
            raise ProfileError(f"board model/config mismatch in {name}")
        lines.append(
            '    {"%s", "%s", "%s", "%s", "%s", "%s", "%s", '
            '0x%xu, 0x%xu, 0x%xu, 0x%xu, 0x%xu, 0x%xu, 0x%xu, 0x%xu, 0x%xu},' % (
                name, parent, bios_parent, bios, p["board_model"], p["board_family"], p["input"],
                p["cpu_clock_hz"], p["gpu_clock_hz"], p["main_ram_size"], p["vram_size"],
                regions["maincpu:rom"], regions["bankedroms"], regions["countryrom"],
                regions["audiocpu"], regions["qsound"],
            )
        )
    if len(seen) != 43:
        raise ProfileError("profile generator did not emit 43 candidate sets")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--registry", type=Path, default=DEFAULT_REGISTRY)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true", help="fail if output is not regenerated exactly")
    args = parser.parse_args(argv)
    try:
        expected = generate(args.registry)
        if args.check:
            if not args.output.exists() or args.output.read_text(encoding="utf-8") != expected:
                raise ProfileError(f"{args.output} is stale; run {Path(__file__).name}")
        else:
            args.output.parent.mkdir(parents=True, exist_ok=True)
            args.output.write_text(expected, encoding="utf-8")
    except (ProfileError, OSError) as exc:
        print(f"generate_capcom_zn_profiles: {exc}", file=sys.stderr)
        return 2
    if not args.check:
        print(f"wrote {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
