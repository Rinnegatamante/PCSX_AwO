"""Extract unchanged per-game CPLD masks/lambdas from a local MAME source."""
import argparse
import re
from pathlib import Path

def balanced(source,start):
    depth=0
    for pos in range(start,len(source)):
        if source[pos]=='{':depth+=1
        elif source[pos]=='}':
            depth-=1
            if depth==0:return source[start:pos+1]
    raise ValueError('Unbalanced source')
def profiles(source):
    source=re.sub(r'/\*.*?\*/|//[^\n]*','',source,flags=re.S)
    output=[]
    for m in re.finditer(r'void namcos10_(\w+)_state::(?:ns10_(\w+)|init_(mrdrilr2))\([^)]*\)\s*\{',source):
        body=balanced(source,m.end()-1);name=m[2] or m[3]
        perm=re.search(r'm_unscrambler\s*=\s*\[\]\s*\(uint16_t data\)\s*\{\s*return bitswap<16>\(data,([^)]*)\);\s*\}',body)
        if not perm:continue
        kind=1 if m[3] else 0;logic='{}';known=0xffff
        cm=re.search(r'NS10_TYPE2_DECRYPTER(_NONLINEAR)?\([^\n]*ns10_crypto_logic\s*\{',body)
        if cm:
            kind=3 if cm[1] else 2;logic=balanced(body,cm.end()-1)
            if '[] (int iv)' not in logic:logic=logic[:-1]+', nullptr}'
            iv=re.search(r'constexpr uint64_t values\[16\]\s*\{([^}]*)\}',logic)
            if iv:
                known=sum(1<<i for i,t in enumerate(iv[1].split(',')) if t.strip() and t.strip()!='UNKNOWN')
        if kind==1:known=sum(1<<i for i in (3,4,5,9,11,13,15))
        xor=0x5300 if m[1]=='memio' else 0xaaaa
        output.append((name,kind,perm[1],logic,known,xor))
    return output

def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('mame_driver',type=Path)
    args=parser.parse_args();source=args.mame_driver.read_text();rows=profiles(source)
    text='// SPDX-License-Identifier: BSD-3-Clause\n// Profile equations copyright Andreas Naive; source MAME namcos10.cpp.\n// Generated by namcos10_crypto_generate.py; do not edit.\n'
    for name,kind,perm,logic,known,xor in rows:
        typename='TableLogic' if kind==3 else 'Logic'
        if kind in (2,3):text+=f'static const {typename} logic_{name}{logic};\n'
        text+=f'static const Profile profile_{name}={{"{name}",{kind},0x{known:04x},0x{xor:04x}, {{{perm}}},'+(f'&logic_{name}' if kind==2 else 'nullptr')+','+(f'&logic_{name}' if kind==3 else 'nullptr')+'};\n'
    text+='static const Profile *const profiles[]={'+','.join('&profile_'+r[0] for r in rows)+'};\n'
    aliases=[]
    names={r[0] for r in rows}
    for game,config in re.findall(r'^GAME\(\s*\d+,\s*(\w+),\s*\w+,\s*ns10_(\w+),',source,re.M):
        if config in names and game!=config:aliases.append(f'{{"{game}",&profile_{config}}}')
    text+='static const Alias aliases[]={'+','.join(aliases)+'};\n'
    Path(__file__).with_name('namcos10_crypto_profiles.inc').write_text(text)
    print('Profiles:',', '.join(r[0] for r in rows));print('Encrypted profiles:',sum(r[1]!=0 for r in rows))
if __name__=='__main__':main()
