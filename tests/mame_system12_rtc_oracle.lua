-- Transient real-H8 SCI1 -> Epson R4543 RTC read probe for System 12.
if _G.SYSTEM12_RTC_PROBE_DONE then return end
_G.SYSTEM12_RTC_PROBE_DONE = true

local m = manager.machine
local sub = m.memory.regions[':sub']
local mainrom = m.memory.regions[':maincpu:rom']
local subcpu = m.devices[':sub']
local subspace = subcpu and subcpu.spaces['program']
local rtc = m.devices[':rtc']
assert(sub and sub.size == 0x80000, 'missing System 12 H8 ROM region')
assert(mainrom and mainrom.size >= 8, 'missing MIPS boot ROM region')
assert(subcpu and subspace and rtc, 'missing H8 program space or RTC')

local function putword(region, address, value)
  region:write_u8(address, math.floor(value / 256) % 256)
  region:write_u8(address + 1, value % 256)
end

local function stamp(t)
  return string.format('%d:%018d', t.seconds, t.attoseconds)
end

-- Keep the MIPS CPU away from the unmodified game while the H8 probe runs.
mainrom:write_u32(0, 0x0bf00000) -- J bfc00000
mainrom:write_u32(4, 0x00000000) -- delay-slot NOP

local rtc_regs = rtc.items['0/m_regs']
assert(rtc_regs, 'MAME RTC save item 0/m_regs missing')
local rtc_item = emu.item(rtc_regs)
assert(rtc_item.size == 4 and rtc_item.count == 7,
  string.format('unexpected RTC item shape size=%d count=%d', rtc_item.size, rtc_item.count))
local rtc_curbit = emu.item(rtc.items['0/m_curbit'])
local rtc_data = emu.item(rtc.items['0/m_data'])
local rtc_clk = emu.item(rtc.items['0/m_clk'])
local rtc_ce = emu.item(rtc.items['0/m_ce'])
local seed = { 0x00, 0x00, 0x12, 0x07, 0x04, 0x10, 0x26 }
for i, value in ipairs(seed) do rtc_item:write(i - 1, value) end
for i, value in ipairs(seed) do
  assert(rtc_item:read(i - 1) == value, 'RTC seed readback mismatch')
end
print(string.format('H8RTC_SEED bytes=00,00,12,07,04,10,26 item_size=%d item_count=%d',
  rtc_item.size, rtc_item.count))

-- The bytecode is generated by check_mame_system12_rtc.py.  Port B.5 and
-- port A.0 select the RTC; SCI1 emits sync clock and receives RDR bytes.
putword(sub, 0, 0)
putword(sub, 2, 0x0100)
local firmware = { FIRMWARE }
for i, word in ipairs(firmware) do putword(sub, 0x100 + (i - 1) * 2, word) end

local MAX_RAW = 96
local raw_count = 0
local raw_tap = subspace:install_read_tap(0xffffbc, 0xffffbd, 'system12-rtc-sci-reads',
  function(offset, data, mem_mask)
    if raw_count >= MAX_RAW then return end
    local address = offset + ((mem_mask & 0xff00) ~= 0 and 0 or 1)
    local value
    if (mem_mask & 0xff00) ~= 0 then value = math.floor(data / 256) % 256
    else value = data % 256 end
    raw_count = raw_count + 1
    print(string.format('H8RTC_REG address=%06x value=%02x time=%s pc=%s',
      address, value, stamp(m.time), tostring(subcpu.state.PC.value)))
  end)
_G.SYSTEM12_RTC_RAW_TAP = raw_tap

local observations = 0
local shared_tap = subspace:install_write_tap(0x080000, 0x080007, 'system12-rtc-shared-stores',
  function(offset, data, mem_mask)
    local value
    if (mem_mask & 0xff00) ~= 0 then value = math.floor(data / 256) % 256
    else value = data % 256 end
    observations = observations + 1
    local address = offset + ((mem_mask & 0xff00) ~= 0 and 0 or 1)
    print(string.format('H8RTC_STORE address=%06x value=%02x time=%s pc=%s curbit=%d data=%d clk=%d ce=%d',
      address, value, stamp(m.time), tostring(subcpu.state.PC.value),
      rtc_curbit:read(0), rtc_data:read(0), rtc_clk:read(0), rtc_ce:read(0)))
    if observations == 8 then
      print('H8RTC_CAPTURE_COMPLETE')
      m:exit()
    end
  end)
_G.SYSTEM12_RTC_SHARED_TAP = shared_tap

local resets = 0
emu.add_machine_reset_notifier(function()
  resets = resets + 1
  local t = m.time
  print(string.format('H8RTC_RESET n=%d time=%s pc=%s',
    resets, stamp(t), tostring(subcpu.state.PC.value)))
end)

m:soft_reset()
